"""Mathematical pivot scoring (Spec 2).

Score = w1*ExpectedInfoGain + w2*CorroborationValue - w3*HopDistancePenalty
        - w4*ExecutionCost

Hop distance is measured from the seed entity set. Entities more than 2 hops
away are penalized unless they share a corroborated identifier with a seed
(prevents six-degrees-of-separation scope explosion). Candidates that can
verify/refute an open HYPOTHESIS or SINGLE_SOURCE_LEAD receive a corroboration
boost. Scoring is pure and deterministic — same inputs, same pivots.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Iterable, Optional

from hub.erkg.graph import GraphView
from hub.models import (
    EdgeType,
    EntityType,
    EpistemicStatus,
    ExecutionMode,
    Hypothesis,
    HypothesisStatus,
    PivotCandidate,
    PivotWeights,
    param_hash,
    short_id,
)
from hub.tools import capabilities as cap_registry

#: Fast python-native collectors that must run before slow theHarvester on a domain.
_FAST_DOMAIN_TOOLS = frozenset({
    "dns_lookup", "tls_cert", "rdap_lookup", "virustotal_lookup",
    "photon_crawler",
})
#: Fastest yields for initial domain resolution/certificate/ASN coverage.
_PRIORITY_DOMAIN_TOOLS = frozenset({
    "dns_lookup", "virustotal_lookup", "tls_cert",
})
#: High-precision username search tools that should precede broad snscrape probes.
_USERNAME_PRIORITY_TOOLS = frozenset({"sherlock", "maigret"})
#: Infrastructure-corroboration pivots once a seed domain resolves to an IP.
_INFRA_IP_TOOLS = frozenset({"shodan_lookup", "censys_lookup"})
_INFRA_DOMAIN_TOOLS = frozenset({"rdap_lookup", "http_headers"})


@dataclass
class EntitySignal:
    """Per-entity epistemic signal used by the scorer."""

    max_confidence: float = 0.30
    has_unverified: bool = False
    contradicted: bool = False
    has_claims: bool = False
    #: Entity was explicitly supplied by the user (USER_PROVIDED_SEED provenance).
    is_user_seed: bool = False
    #: Entity was generated by the bounded permutation engine (guessed handle/email).
    is_hypothesis_origin: bool = False
    entity_type: str = ""


@dataclass
class PivotRanking:
    """Ranked pivots plus counters needed by stopping conditions."""

    selected: list[PivotCandidate] = field(default_factory=list)
    all_candidates: list[PivotCandidate] = field(default_factory=list)
    above_threshold: int = 0
    generated: int = 0
    threshold: float = 0.0

    @property
    def best(self) -> Optional[PivotCandidate]:
        return self.selected[0] if self.selected else None


def entity_signals(graph: GraphView) -> dict[str, EntitySignal]:
    """Compute epistemic signals for every entity from its claims."""
    signals: dict[str, EntitySignal] = {
        entity_id: EntitySignal() for entity_id in graph.entities
    }
    for entity_id, entity in graph.entities.items():
        signal = signals[entity_id]
        metadata = entity.metadata or {}
        provenance = str(metadata.get("provenance") or "").strip().upper()
        signal.entity_type = entity.type.value
        signal.is_user_seed = provenance in {
            "USER_PROVIDED_SEED", "EMAIL_DERIVED_DOMAIN",
            "EMAIL_DERIVED_USERNAME",
        }
        signal.is_hypothesis_origin = (
            provenance in {"USER_DERIVED_HYPOTHESIS", "HYPOTHESIS", "GUESS"}
            or str(metadata.get("origin") or "").strip().lower() == "hypothesis"
        )
    for claim in graph.claims:
        subject_signal = signals.get(claim.subject_id)
        if subject_signal is not None:
            subject_signal.has_claims = True
            if claim.predicate == "IDENTIFIED_AS":
                subject_signal.max_confidence = max(subject_signal.max_confidence,
                                                    claim.confidence)
            else:
                subject_signal.max_confidence = max(subject_signal.max_confidence,
                                                    claim.confidence)
            if claim.status in (EpistemicStatus.SINGLE_SOURCE_LEAD,
                                EpistemicStatus.HYPOTHESIS):
                subject_signal.has_unverified = True
            if claim.status == EpistemicStatus.CONTRADICTED:
                subject_signal.contradicted = True
        if claim.object_id:
            object_signal = signals.get(claim.object_id)
            if object_signal is not None:
                object_signal.has_claims = True
                object_signal.max_confidence = max(object_signal.max_confidence,
                                                   claim.confidence)
                if claim.status in (EpistemicStatus.SINGLE_SOURCE_LEAD,
                                    EpistemicStatus.HYPOTHESIS):
                    object_signal.has_unverified = True
                if claim.status == EpistemicStatus.CONTRADICTED:
                    object_signal.contradicted = True
    return signals


class PivotScorer:
    """Generates and ranks (TargetEntity, ToolCapability) pivot candidates."""

    def __init__(self, weights: Optional[PivotWeights] = None,
                 min_threshold: float = 0.12, top_k: int = 5,
                 max_per_entity: int = 2, max_per_tool: int = 2,
                 max_entities: int = 500):
        self.weights = (weights or PivotWeights()).normalized()
        self.min_threshold = float(min_threshold)
        self.top_k = int(top_k)
        self.max_per_entity = int(max_per_entity)
        self.max_per_tool = int(max_per_tool)
        self.max_entities = int(max_entities)

    # ── generation ─────────────────────────────────────────────────

    def rank(self, graph: GraphView, hypotheses: Iterable[Hypothesis], *,
             allowed_tool_ids: Iterable[str],
             executed_keys: Optional[set[tuple[str, str, str]]] = None,
             blocked_tool_ids: Optional[Iterable[str]] = None,
             successful_entity_ids: Optional[Iterable[str]] = None,
             ) -> PivotRanking:
        # In-run circuit breaker: tools that already failed with RATE_LIMITED /
        # AUTHORIZATION_REQUIRED / MISSING_BINARY in this investigation are never
        # selected again, regardless of any other score bonus.
        blocked = {t.lower() for t in (blocked_tool_ids or set())}
        allowed = {t.lower() for t in allowed_tool_ids} - blocked
        executed = executed_keys or set()
        signals = entity_signals(graph)
        hypothesis_by_entity: dict[str, list[Hypothesis]] = {}
        for hypothesis in hypotheses:
            if hypothesis.status != HypothesisStatus.OPEN:
                continue
            if hypothesis.target_entity_id:
                hypothesis_by_entity.setdefault(hypothesis.target_entity_id, []).append(hypothesis)

        hop_distances = graph.hop_distances()
        executed_per_entity_tool: dict[tuple[str, str], int] = {}
        executed_entities: set[str] = set()
        executed_tools: set[str] = set()
        tool_run_counts: dict[str, int] = {}
        for entity_id, tool_id, _ in executed:
            key = (entity_id, tool_id)
            executed_per_entity_tool[key] = executed_per_entity_tool.get(key, 0) + 1
            executed_entities.add(entity_id)
            executed_tools.add(tool_id)
            tool_run_counts[tool_id] = tool_run_counts.get(tool_id, 0) + 1
        successful_entities = (
            executed_entities if successful_entity_ids is None
            else {str(entity_id) for entity_id in successful_entity_ids}
        )
        # Seeds that have been attempted but only produced EMPTY/ERROR results:
        # their next highest-prior tool gets a rescue bonus so every username and
        # domain seed receives at least one productive run.
        uncovered_seed_entities = {
            seed_id for seed_id in graph.seed_entity_ids
            if seed_id in graph.entities
            and seed_id in executed_entities
            and seed_id not in successful_entities
        }

        # Phase 11 seed-first coverage: every primary seed entity type must get
        # at least one tool before guessed HYPOTHESIS permutations are allowed to
        # compete on score (usernames, emails, phones, domains, etc.).
        primary_seed_types = {
            EntityType.USERNAME, EntityType.EMAIL, EntityType.PHONE,
            EntityType.DOMAIN, EntityType.IP, EntityType.URL,
        }
        uncovered_seed_types = {
            entity.type for seed_id in graph.seed_entity_ids
            if seed_id in graph.entities
            and (entity := graph.entities[seed_id]).type in primary_seed_types
            and seed_id not in successful_entities
        }
        seed_coverage_complete = not uncovered_seed_types
        candidate_flags: dict[str, tuple[bool, bool, bool]] = {}

        # Phase 16: once a root domain has an evidence-backed RESOLVES_TO IP,
        # pivot onto that primary IP with Shodan/Censys and onto the root domain
        # with RDAP/HTTP headers before low-yield secondary username/email tools.
        infrastructure_ips: set[str] = set()
        infrastructure_domains: set[str] = set()
        for claim in graph.claims:
            if claim.predicate != EdgeType.RESOLVES_TO.value:
                continue
            if claim.status in {EpistemicStatus.HYPOTHESIS,
                                 EpistemicStatus.CONTRADICTED,
                                 EpistemicStatus.COLLECTION_FAILURE}:
                continue
            subject = graph.entities.get(claim.subject_id)
            obj = graph.entities.get(claim.object_id) if claim.object_id else None
            if subject is None or obj is None:
                continue
            if subject.type is EntityType.DOMAIN and obj.type is EntityType.IP:
                infrastructure_domains.add(subject.entity_id)
                infrastructure_ips.add(obj.entity_id)

        candidates: list[PivotCandidate] = []
        ordered_entities = sorted(
            graph.entities.values(),
            key=lambda e: (hop_distances.get(e.entity_id, 3), e.type.value, e.entity_id),
        )[: self.max_entities]
        for entity in ordered_entities:
            signal = signals.get(entity.entity_id, EntitySignal())
            capabilities = cap_registry.for_entity(entity.type)
            for capability in capabilities:
                if capability.tool_id.lower() not in allowed:
                    continue
                params = cap_registry.build_params_for_entity(
                    capability, entity.type, entity.canonical_value)
                if params is None:
                    continue
                errors = cap_registry.validate_params(capability, params)
                if errors:
                    continue
                phash = param_hash(capability.tool_id, params)
                if (entity.entity_id, capability.tool_id, phash) in executed:
                    continue
                hypothesis = self._matching_hypothesis(
                    hypothesis_by_entity.get(entity.entity_id, []), capability.tool_id)
                seed_type_uncovered = bool(
                    signal.is_user_seed and entity.type in uncovered_seed_types)
                tool_unused = capability.tool_id.lower() not in executed_tools
                tool_saturated = (tool_run_counts.get(capability.tool_id, 0) >= 2
                                  and not seed_coverage_complete)
                seed_rescue = bool(signal.is_user_seed
                                   and entity.entity_id in uncovered_seed_entities)
                fast_domain = bool(
                    signal.is_user_seed and entity.type == EntityType.DOMAIN
                    and capability.tool_id.lower() in _FAST_DOMAIN_TOOLS)
                priority_domain = bool(
                    signal.is_user_seed and entity.type == EntityType.DOMAIN
                    and capability.tool_id.lower() in _PRIORITY_DOMAIN_TOOLS)
                username_priority = bool(
                    signal.is_user_seed and entity.type == EntityType.USERNAME
                    and capability.tool_id.lower() in _USERNAME_PRIORITY_TOOLS)
                infrastructure = bool(
                    (entity.type is EntityType.IP
                     and entity.entity_id in infrastructure_ips
                     and capability.tool_id.lower() in _INFRA_IP_TOOLS)
                    or (entity.type is EntityType.DOMAIN
                        and entity.entity_id in infrastructure_domains
                        and capability.tool_id.lower() in _INFRA_DOMAIN_TOOLS))
                candidate = self.score(
                    entity_id=entity.entity_id,
                    entity_value=entity.canonical_value,
                    entity_type=entity.type.value,
                    capability=capability,
                    params=params,
                    param_hash_value=phash,
                    hop=hop_distances.get(entity.entity_id, 3),
                    shares_identifier=graph.shares_corroborated_identifier(entity.entity_id),
                    signal=signal,
                    hypothesis_id=hypothesis.hypothesis_id if hypothesis else None,
                    prior_runs_on_entity=executed_per_entity_tool.get(
                        (entity.entity_id, capability.tool_id), 0),
                    seed_type_uncovered=seed_type_uncovered,
                    tool_unused=tool_unused,
                    tool_saturated=tool_saturated,
                    hypothesis_boost_allowed=seed_coverage_complete,
                    seed_rescue=seed_rescue,
                    fast_domain=fast_domain,
                    priority_domain=priority_domain,
                    username_priority=username_priority,
                    infrastructure=infrastructure,
                )
                candidate_flags[candidate.pivot_id] = (
                    signal.is_user_seed, signal.is_hypothesis_origin,
                    infrastructure)
                candidates.append(candidate)

        # Round-robin across seed entities: every seed gets one pivot before any
        # seed receives a second, so two usernames cannot be starved by six fast
        # domain collectors. Within an attempt round, score/bonuses apply.
        seed_attempt_counts: dict[str, int] = {}
        preferred_username_attempted: set[str] = set()
        for entity_id, _tool_id, _param_hash_value in executed:
            if entity_id in graph.seed_entity_ids:
                seed_attempt_counts[entity_id] = (
                    seed_attempt_counts.get(entity_id, 0) + 1)
                if _tool_id.lower() in _USERNAME_PRIORITY_TOOLS:
                    preferred_username_attempted.add(entity_id)

        def sort_key(candidate: PivotCandidate) -> tuple:
            is_seed, is_hypothesis, is_infrastructure = candidate_flags.get(
                candidate.pivot_id, (False, False, False))
            preferred_rank = 0
            if is_infrastructure:
                # A freshly confirmed primary IP is the highest-value pivot.
                tier = -1
                attempt_rank = 0
            elif is_seed:
                tier = 0          # user-provided seeds always rank first
                attempt_rank = seed_attempt_counts.get(candidate.entity_id, 0)
                # Every seed username must be scanned by sherlock/maigret before
                # broad github/snscrape probes on that same seed.
                seed_entity = graph.entities.get(candidate.entity_id)
                if (seed_entity is not None
                        and seed_entity.type == EntityType.USERNAME
                        and candidate.entity_id not in preferred_username_attempted):
                    preferred_rank = (0 if candidate.tool_id.lower()
                                      in _USERNAME_PRIORITY_TOOLS else 1)
            elif is_hypothesis and not seed_coverage_complete:
                tier = 2          # guessed permutations starve until seeds covered
                attempt_rank = 0
            else:
                tier = 1
                attempt_rank = 0
            return (tier, attempt_rank, preferred_rank, -candidate.score,
                    candidate.entity_id, candidate.tool_id)

        candidates.sort(key=sort_key)
        # Threshold remains an absolute user-configured stop condition; seed-first
        # ordering applies among admissible pivots only.
        above = [c for c in candidates if c.score >= self.min_threshold]
        selected = self._diversified(above)
        return PivotRanking(selected=selected, all_candidates=candidates,
                            above_threshold=len(above), generated=len(candidates),
                            threshold=self.min_threshold)

    def _diversified(self, candidates: list[PivotCandidate]) -> list[PivotCandidate]:
        chosen: list[PivotCandidate] = []
        per_entity: dict[str, int] = {}
        per_tool: dict[str, int] = {}
        for candidate in candidates:
            if len(chosen) >= self.top_k:
                break
            if per_entity.get(candidate.entity_id, 0) >= self.max_per_entity:
                continue
            if per_tool.get(candidate.tool_id, 0) >= self.max_per_tool:
                continue
            chosen.append(candidate)
            per_entity[candidate.entity_id] = per_entity.get(candidate.entity_id, 0) + 1
            per_tool[candidate.tool_id] = per_tool.get(candidate.tool_id, 0) + 1
        if len(chosen) < self.top_k:
            # Relax diversity when the graph is thin, keeping deterministic order.
            for candidate in candidates:
                if candidate not in chosen:
                    chosen.append(candidate)
                if len(chosen) >= self.top_k:
                    break
        return chosen

    # ── scoring ────────────────────────────────────────────────────

    def score(self, *, entity_id: str, entity_value: str, entity_type: str,
              capability, params: dict, param_hash_value: str, hop: int,
              shares_identifier: bool, signal: EntitySignal,
              hypothesis_id: Optional[str], prior_runs_on_entity: int = 0,
              seed_type_uncovered: bool = False, tool_unused: bool = False,
              tool_saturated: bool = False,
              hypothesis_boost_allowed: bool = True,
              seed_rescue: bool = False, fast_domain: bool = False,
              priority_domain: bool = False, username_priority: bool = False,
              infrastructure: bool = False,
              ) -> PivotCandidate:
        expected_info_gain = self._expected_info_gain(capability, signal,
                                                      prior_runs_on_entity)
        corroboration_value = self._corroboration_value(
            signal, hypothesis_id,
            allow_hypothesis_boost=hypothesis_boost_allowed)
        hop_penalty = self._hop_penalty(hop, shares_identifier)
        execution_cost = self._execution_cost(capability)
        weights = self.weights
        score = (
            weights.w1_info_gain * expected_info_gain
            + weights.w2_corroboration * corroboration_value
            - weights.w3_hop_penalty * hop_penalty
            - weights.w4_cost * execution_cost
        )
        # Phase 11 seed-first expansion priorities.
        if signal.is_user_seed:
            score += 0.35
        if seed_type_uncovered:
            score += 0.10
        if tool_unused and signal.is_user_seed:
            score += 0.06
        if tool_saturated and signal.is_user_seed:
            score -= 0.08
        # Phase 14: every seed username/domain must get productive coverage.
        if seed_rescue:
            score += 0.25
        if fast_domain:
            score += 0.25
        if priority_domain:
            score += 0.12
        if infrastructure:
            score += 0.22
        # sherlock/maigret already outrank snscrape by prior yield; no extra
        # score inflation here (keeps an explicit high min_pivot_threshold usable).
        rationale_parts = []
        if signal.is_user_seed:
            rationale_parts.append("USER_PROVIDED_SEED")
        if seed_type_uncovered:
            rationale_parts.append("uncovered seed type")
        if seed_rescue:
            rationale_parts.append("uncovered-seed rescue")
        if fast_domain:
            rationale_parts.append("fast domain collector")
        if priority_domain:
            rationale_parts.append("high-yield domain collector")
        if infrastructure:
            rationale_parts.append("infrastructure corroboration (resolved primary IP)")
        if username_priority:
            rationale_parts.append("preferred username tool")
        if tool_unused and signal.is_user_seed:
            rationale_parts.append("new tool for seed wave")
        if signal.is_hypothesis_origin and not hypothesis_boost_allowed:
            rationale_parts.append("guessed hypothesis (capped until seeds covered)")
        if hypothesis_id:
            rationale_parts.append("corroborates open hypothesis")
        if signal.has_unverified:
            rationale_parts.append("target has unverified claims")
        if hop > 2:
            rationale_parts.append(f"hop {hop} from seed"
                                   + (" (identifier exemption)" if shares_identifier else ""))
        if capability.execution_mode == ExecutionMode.ACTIVE_RECON:
            rationale_parts.append("active recon")
        rationale_parts.append(f"prior yield {capability.prior_yield:.2f}")
        return PivotCandidate(
            pivot_id=short_id("piv", entity_id, capability.tool_id, param_hash_value),
            entity_id=entity_id,
            tool_id=capability.tool_id,
            params=dict(params),
            expected_info_gain=round(max(0.0, min(1.0, expected_info_gain)), 4),
            corroboration_value=round(max(0.0, min(1.0, corroboration_value)), 4),
            hop_distance=hop,
            hop_penalty=round(hop_penalty, 4),
            execution_cost=round(execution_cost, 4),
            score=round(score, 4),
            hypothesis_id=hypothesis_id,
            rationale=f"{entity_type} {entity_value}: " + "; ".join(rationale_parts),
        )

    def _expected_info_gain(self, capability, signal: EntitySignal,
                            prior_runs: int) -> float:
        # Unconfirmed targets have the most to reveal; confirmed ones little.
        uncertainty = 1.0 - max(0.0, min(1.0, signal.max_confidence))
        novelty = 1.0 - min(0.75, 0.25 * prior_runs)
        return max(0.0, min(1.0, capability.prior_yield * (0.35 + 0.65 * uncertainty)
                           * novelty))

    def _corroboration_value(self, signal: EntitySignal,
                             hypothesis_id: Optional[str],
                             *, allow_hypothesis_boost: bool = True) -> float:
        # Guessed planner permutations must never receive the full corroboration
        # boost meant for discovered leads: cap at 0.20 until every primary seed
        # has at least one executed tool.
        if signal.is_hypothesis_origin and not allow_hypothesis_boost:
            return 0.20
        if hypothesis_id:
            return 1.0
        if signal.contradicted:
            return 0.8
        if signal.has_unverified:
            return 0.6
        return 0.0

    def _hop_penalty(self, hop: int, shares_identifier: bool) -> float:
        if hop <= 2:
            return 0.0
        penalty = min(1.0, 0.5 + 0.25 * (hop - 2))
        if shares_identifier:
            penalty *= 0.2
        return max(0.0, min(1.0, penalty))

    def _execution_cost(self, capability) -> float:
        cost = min(1.0, max(0.0, capability.timeout_sec / 600.0)) * 0.7
        if capability.execution_mode == ExecutionMode.ACTIVE_RECON:
            cost += 0.3
        if capability.authorization_required:
            cost += 0.2
        return max(0.0, min(1.0, cost))

    def _matching_hypothesis(self, hypotheses: list[Hypothesis],
                             tool_id: str) -> Optional[Hypothesis]:
        for hypothesis in hypotheses:
            if not hypothesis.proposed_tool_ids or tool_id in hypothesis.proposed_tool_ids:
                return hypothesis
        return None


